    const old = document.getElementById('hg-fab');
    if (old) old.remove();
    if (!g) return;
    const b = document.createElement('button');
    b.id = 'hg-fab';
    b.type = 'button';
    b.className = 'hg-fab';
    b.title = 'কীভাবে ব্যবহার করবেন · শব্দের মানে';
    b.innerHTML = '<i class="bi bi-question-lg"></i><span>গাইড</span>';
    b.onclick = () => this.open(toolId);
    document.body.appendChild(b);

